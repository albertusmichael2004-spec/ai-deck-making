from pathlib import Path
from typing import Protocol


class FileBackend(Protocol):
    def capabilities(self) -> dict: ...
    def create(self, slides: list[dict], canvas: dict, destination: Path, template: dict | None = None) -> dict: ...
    def inspect(self, source: Path) -> dict: ...
    def patch(self, source: Path, destination: Path, patch: dict, scope: dict) -> dict: ...
    def validate(self, source: Path) -> dict: ...


class NativeProbeBackend(Protocol):
    def probe(self, snapshot_directory: Path | None = None) -> dict: ...


class RenderBackend(Protocol):
    def render(self, source: Path, output: Path) -> dict: ...
